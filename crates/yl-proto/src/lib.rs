//! Wire protocol shared by the Host and viewers.
//!
//! Frames on the wire are `u32 big-endian payload length || bincode(payload)`.
//! TLS with ALPN `yuanlian/1` is the transport. See `docs/protocol.md`.

use anyhow::{bail, Context, Result};
use serde::{de::DeserializeOwned, Deserialize, Serialize};
use sha2::{Digest, Sha256};
use tokio::io::{AsyncRead, AsyncReadExt, AsyncWrite, AsyncWriteExt};

pub mod auth;

pub const PROTOCOL_VERSION: u16 = 2;
pub const ALPN: &[u8] = b"yuanlian/1";
pub const MAX_MESSAGE_BYTES: usize = 32 * 1024 * 1024;
pub const DEFAULT_PORT: u16 = 24_800;
pub const TLS_SERVER_NAME: &str = "yuanlian.local";

/// Viewer feature bits advertised in `ClientHello`.
pub const FEATURE_FILE_TRANSFER: u32 = 1 << 0;
pub const FEATURE_TEXT_INPUT: u32 = 1 << 1;
pub const FEATURE_SESSION_TICKET: u32 = 1 << 2;

/// Permission bits carried by a session ticket and intersected with the
/// Host's local policy. A missing bit always denies.
pub const PERMISSION_VIEW: u32 = 1 << 0;
pub const PERMISSION_CONTROL: u32 = 1 << 1;
pub const PERMISSION_FILE_READ: u32 = 1 << 2;
pub const PERMISSION_FILE_WRITE: u32 = 1 << 3;
pub const PERMISSION_FILE_DELETE: u32 = 1 << 4;
pub const PERMISSION_ALL: u32 = PERMISSION_VIEW
    | PERMISSION_CONTROL
    | PERMISSION_FILE_READ
    | PERMISSION_FILE_WRITE
    | PERMISSION_FILE_DELETE;

pub fn permission_summary(bits: u32) -> String {
    let mut names = Vec::new();
    if bits & PERMISSION_VIEW != 0 {
        names.push("查看");
    }
    if bits & PERMISSION_CONTROL != 0 {
        names.push("控制");
    }
    if bits & PERMISSION_FILE_READ != 0 {
        names.push("读取文件");
    }
    if bits & PERMISSION_FILE_WRITE != 0 {
        names.push("写入文件");
    }
    if bits & PERMISSION_FILE_DELETE != 0 {
        names.push("删除文件");
    }
    if names.is_empty() {
        "无权限".to_string()
    } else {
        names.join("、")
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ClientHello {
    pub protocol_version: u16,
    pub client_name: String,
    pub client_id: String,
    /// The viewer intends to send keyboard/mouse input. The Host still decides.
    pub request_input: bool,
    pub features: u32,
    /// Signed short-lived session ticket. `None` is the explicit anonymous
    /// development mode; a production Host rejects it unless configured to.
    pub session_ticket: Option<String>,
    /// 64 hex characters generated by the viewer. The ticket carries its hash,
    /// binding the ticket to this connection attempt.
    pub session_nonce: String,
}

